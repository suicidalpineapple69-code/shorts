// The performance: golem keyframes, hero modes and camera moves for each round.
// Positions are world coordinates (1 unit = 1 block). Golem faces +z, its "P" arm is on +x.
// A key value of 'rest' means the arm hangs naturally; 'hero' means "the hero's chest".
import { ROUNDS, LAND, GRAB } from './plan.js';

export const GOLEM_ROOT = [0, 0, -2.4];
const STAND = { hipY: 2.78, pitch: 0.06 };

const reach = (R) => [R.spawn[0] - 0.05, 1.7, R.spawn[2] - 0.35];
const up = (x, y, z) => [x, y, z];

// shared opening for the grab rounds: lean, reach, close, lift
function grabKeys(R, extra) {
  const k = {
    hipY: [[0, STAND.hipY], [0.55, 2.6], [GRAB, 2.15], [GRAB + 0.35, 2.55]],
    pitch: [[0, STAND.pitch], [0.55, 0.35], [GRAB, 0.72], [GRAB + 0.35, 0.25]],
    yaw: [[0, 0], [GRAB, Math.atan2(R.spawn[0], R.spawn[2] - GOLEM_ROOT[2]) * 0.8]],
    P: [[0, 'rest'], [0.5, 'rest'], [GRAB - 0.05, reach(R)], [GRAB + 0.08, reach(R)]],
    N: [[0, 'rest']],
    headPitch: [[0, 0], [0.6, 0.35], [GRAB, 0.45], [GRAB + 0.4, 0.0]],
  };
  for (const key of Object.keys(extra)) k[key] = (k[key] || []).concat(extra[key]);
  return k;
}

